"""Content/runtime identities without importing descriptor or model backends.

Versions describe installed distributions, not arbitrary unversioned source
edits. Maintained forks must use honest distinct versions. Execution paths,
CPU counts and unrelated installed packages are deliberately excluded.
"""
from __future__ import annotations

import importlib.metadata
import hashlib
import json
import platform
import sys
from pathlib import Path
from typing import Any, Mapping, Sequence


class RuntimeIdentityError(ValueError):
    """Saved scientific objects cannot be reused in this runtime."""


_DESCRIPTOR_PACKAGES = {
    "morgan": ("rdkit",), "mfp": ("rdkit",), "maccs": ("rdkit",),
    "maf": ("rdkit",), "rdkit2d": ("rdkit",),
    "drfp": ("drfp", "rdkit"), "ohe": ("scikit-learn", "joblib"),
    "fisd": ("rdkit", "torch", "torch-geometric", "networkx"),
    "molmetalm": ("rdkit", "torch", "transformers", "tokenizers", "huggingface-hub", "safetensors"),
    "chemical_vae": ("rdkit", "torch"),
}
_MODEL_PACKAGES = {
    "rf": (), "svm": (), "xgb": ("xgboost",), "lightgbm": ("lightgbm",),
    "autogluon": ("autogluon.tabular", "autogluon.core", "autogluon.common", "autogluon.features",
                  "lightgbm", "catboost", "xgboost", "torch", "fastai"),
}


def _versions(names: Sequence[str]) -> dict[str, str | None]:
    result = {}
    for name in sorted(set(names)):
        try:
            result[name] = importlib.metadata.version(name)
        except importlib.metadata.PackageNotFoundError:
            # Metadata-only/stub checks may have no optional backend installed.
            # An actual descriptor/estimator still must import its own backend.
            result[name] = None
    return result


def _rdkit_namespace_identity() -> dict[str, Any]:
    """Hash effective target-provider files without importing RDKit itself.

    Shared rdkit/ files may have been overwritten by rdkit-pypi while both
    distribution versions stay unchanged. Hash actual bytes, not the declared
    RECORD digests. The separate namespace acceptance check verifies those
    declarations; this identity also represents an unchanged historical
    installation honestly. Prefixes, mtimes and generated bytecode are absent.
    """
    try:
        distribution = importlib.metadata.distribution("rdkit")
    except importlib.metadata.PackageNotFoundError as exc:
        raise RuntimeIdentityError("RDKit 运行时身份缺少目标 rdkit distribution；请检查环境或回到原历史环境") from exc
    files = []
    for record in distribution.files or []:
        name = str(record).replace("\\", "/")
        if not name.startswith(("rdkit/", "rdkit.libs/")) or name.lower().endswith(".pyc"):
            continue
        if record.hash is None:
            continue
        if ".." in name.split("/"):
            raise RuntimeIdentityError("RDKit RECORD 含越界路径，无法建立运行时内容身份")
        digest = hashlib.sha256()
        try:
            with Path(distribution.locate_file(record)).open("rb") as handle:
                for chunk in iter(lambda: handle.read(1024 * 1024), b""):
                    digest.update(chunk)
        except OSError as exc:
            raise RuntimeIdentityError(f"RDKit 运行时身份文件缺失或不可读取：{name}；请检查环境，不要复用旧特征或模型") from exc
        files.append({"path": name, "sha256": digest.hexdigest()})
    if not files:
        raise RuntimeIdentityError("RDKit RECORD 未提供可核验的 namespace 文件，无法建立运行时内容身份")
    files.sort(key=lambda item: item["path"])
    encoded = json.dumps(files, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode("utf-8")
    return {"schema": "yonod.rdkit-namespace-content/v1", "file_count": len(files),
            "sha256": hashlib.sha256(encoded).hexdigest()}


def _descriptor_spec(item: str | Mapping[str, Any]) -> tuple[str, Mapping[str, Any]]:
    if isinstance(item, str):
        return item.lower(), {}
    name = item.get("descriptor") or item.get("algorithm")
    if not name and item.get("kind") == "fold_transform":
        name = "ohe"
    if not isinstance(name, str):
        raise RuntimeIdentityError("运行时身份缺少描述符名称")
    return name.lower(), item.get("params") or {}


def _asset_reference(reference: str | Path, config_path: Path | str | None) -> Path:
    if config_path is not None:
        from yonod.config.contracts import resolve_config_path
        return resolve_config_path(config_path, str(reference))
    return Path(reference).expanduser().resolve()


def runtime_identity(
    *, descriptors: Sequence[str | Mapping[str, Any]] = (),
    models: Sequence[str] = (), config_path: Path | str | None = None,
    hpo: bool = False,
) -> dict[str, Any]:
    """Collect only selected providers; MolMetaLM validates assets lazily."""
    names = {"numpy", "pandas"} if descriptors or models else set()
    descriptor_records = {}
    for item in descriptors:
        descriptor, params = _descriptor_spec(item)
        if descriptor not in _DESCRIPTOR_PACKAGES:
            raise RuntimeIdentityError(f"未知描述符运行时身份：{descriptor}")
        names.update(_DESCRIPTOR_PACKAGES[descriptor])
        record: dict[str, Any] = {}
        if descriptor == "molmetalm":
            from yonod.descriptors.molmetalm_assets import INPUT_PREPROCESSING_POLICY, validated_asset_identity
            if not isinstance(INPUT_PREPROCESSING_POLICY, str) or not INPUT_PREPROCESSING_POLICY:
                raise RuntimeIdentityError("MolMetaLM 缺少明确的输入预处理策略身份")
            # Input semantics can change while libraries and weights stay fixed.
            record["input_preprocessing_policy"] = INPUT_PREPROCESSING_POLICY
            record["input_max_length"] = params.get("max_length", 512)
            reference = params.get("weight_path")
            if reference is None:
                path = Path(__file__).resolve().parents[1] / "WEIGHTS" / "MolMetaLM-base"
            else:
                path = _asset_reference(reference, config_path)
            record["assets"] = validated_asset_identity(path, asset_sha256=params.get("asset_sha256"))
        elif descriptor == "fisd":
            from yonod.descriptors.trusted_assets import validated_fisd_asset_identity
            reference = params.get("model_dir")
            if reference is None:
                project = Path(__file__).resolve().parents[1]
                path = project / "WEIGHTS" / "FISD"
                legacy = project / "化学描述符相关项目" / "FISD" / "model"
                if not path.exists() and legacy.exists():
                    path = legacy
            else:
                path = _asset_reference(reference, config_path)
            record["assets"] = validated_fisd_asset_identity(path.resolve())
        elif descriptor == "chemical_vae":
            from yonod.descriptors.trusted_assets import validated_chemical_vae_asset_identity
            reference = params.get("model_manifest")
            if not isinstance(reference, str) or not reference:
                raise RuntimeIdentityError("Chemical VAE 运行时身份需要 model_manifest 及其 YAML 定位")
            path = _asset_reference(reference, config_path)
            record["assets"] = validated_chemical_vae_asset_identity(path.resolve())
        descriptor_records[descriptor] = record
    model_names = sorted(set(models))
    for model in model_names:
        if model not in _MODEL_PACKAGES:
            raise RuntimeIdentityError(f"未知模型运行时身份：{model}")
        # Shared sklearn adapters, fold preprocessing and persisted models.
        names.update(("scikit-learn", "scipy", "joblib"))
        names.update(_MODEL_PACKAGES[model])
    if hpo:
        names.update(("optuna", "sqlalchemy"))
    rdkit_namespace = None
    if "rdkit" in names:
        names.add("rdkit-pypi")
        rdkit_namespace = _rdkit_namespace_identity()
    identity = {
        "schema": "yonod.runtime-identity/v1",
        "python": {"implementation": platform.python_implementation(), "version": list(sys.version_info[:3])},
        "descriptors": dict(sorted(descriptor_records.items())),
        "models": model_names,
        "packages": _versions(tuple(names)),
    }
    if rdkit_namespace is not None:
        identity["rdkit_namespace"] = rdkit_namespace
    return identity


def require_runtime_identity(saved: Any, current: Mapping[str, Any]) -> None:
    """Fail before any pickle/joblib loading or descriptor computation."""
    if not isinstance(saved, Mapping) or saved.get("schema") != "yonod.runtime-identity/v1":
        raise RuntimeIdentityError("缺少受支持的运行时身份；请回到原历史环境，或在当前环境重新生成特征并建模")
    if dict(saved) != dict(current):
        raise RuntimeIdentityError("运行时依赖版本、Python 或资产内容与保存身份不一致；请回到原历史环境，或在当前环境重新生成特征并建模")


def artifact_descriptor(manifest: Mapping[str, Any]) -> Mapping[str, Any]:
    metadata = manifest.get("metadata") or {}
    spec = metadata.get("feature_spec")
    if isinstance(spec, Mapping):
        return spec
    if manifest.get("lifecycle") == "fold_transform":
        return {"descriptor": "ohe"}
    raise RuntimeIdentityError("特征包缺少描述符运行时声明；请回到原历史环境或重新生成特征")
