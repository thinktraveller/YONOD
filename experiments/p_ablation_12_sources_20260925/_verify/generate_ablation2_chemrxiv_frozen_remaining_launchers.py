"""Generate the ten remaining frozen-external task launchers and one serial runner.

This utility never starts a model.  It freezes the remaining task order after
the completed Morgan/RF ``full`` and ``minus_a`` tasks, checks every remaining
schema-2 configuration through the dedicated external-test contract, and
writes Bash-only launchers below ``_verify/generated/``.  The generated master
runner starts exactly one headless task at a time, waits for it to exit, then
runs the read-only result verifier before allowing the next task to start.
"""

from __future__ import annotations

import argparse
import stat
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from yonod.benchmark.frozen_external import FrozenExternalTestConfig


PLAN_ID = "ablation2_chemrxiv_frozen_remaining_v1"
COMPLETED = (
    "ablation2_chemrxiv_frozen_morgan_rf_full_v1",
    "ablation2_chemrxiv_frozen_morgan_rf_minus_a_v1",
)
REMAINING = (
    "ablation2_chemrxiv_frozen_morgan_rf_minus_p_v1",
    "ablation2_chemrxiv_frozen_morgan_rf_minus_a_p_v1",
    "ablation2_chemrxiv_frozen_morgan_rf_product_conditions_v1",
    "ablation2_chemrxiv_frozen_morgan_rf_conditions_only_v1",
    "ablation2_chemrxiv_frozen_mfp_lightgbm_full_v1",
    "ablation2_chemrxiv_frozen_mfp_lightgbm_minus_a_v1",
    "ablation2_chemrxiv_frozen_mfp_lightgbm_minus_p_v1",
    "ablation2_chemrxiv_frozen_mfp_lightgbm_minus_a_p_v1",
    "ablation2_chemrxiv_frozen_mfp_lightgbm_product_conditions_v1",
    "ablation2_chemrxiv_frozen_mfp_lightgbm_conditions_only_v1",
)
GENERATED_ROOT = ROOT / "_verify" / "generated" / PLAN_ID
TASK_DIR = GENERATED_ROOT / "tasks"
MASTER = GENERATED_ROOT / "run_remaining_linearly.sh"


def _config_path(task_name: str) -> Path:
    return ROOT / "config" / (task_name + ".yaml")


def _result_root(task_name: str) -> Path:
    return ROOT / "result" / task_name


def _write_immutable(path: Path, text: str, executable: bool = False) -> None:
    """Publish generated text without silently changing a frozen launch plan."""
    if path.exists():
        if path.read_text(encoding="utf-8") != text:
            raise RuntimeError("Refusing to overwrite divergent generated launcher: {0}".format(path))
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(text, encoding="utf-8")
    if executable:
        temporary.chmod(temporary.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    temporary.replace(path)


def _task_launcher(task_name: str) -> str:
    return """#!/usr/bin/env bash
# Generated by {generator}; Bash/Linux only.  This launcher intentionally
# runs in the foreground.  The serial master supplies headless logging/PID.
set -euo pipefail

repo_root="$(cd "$(dirname "${{BASH_SOURCE[0]}}")/../../../.." && pwd)"
cd "$repo_root"
source /home/wangzh685/miniconda3/etc/profile.d/conda.sh
conda activate yonod

exec taskset --cpu-list 0-18 python -u yonod.py <<'YONOD_CONFIG'
config/{task}.yaml
YONOD_CONFIG
""".format(generator=Path(__file__).name, task=task_name)


def _master_runner(task_scripts: list[Path]) -> str:
    script_lines = "\n".join(
        '  "${{script_dir}}/tasks/{0}"'.format(path.name) for path in task_scripts
    )
    completed_config_lines = "\n".join(
        'verify_completed "config/{0}.yaml"'.format(task_name) for task_name in COMPLETED
    )
    return """#!/usr/bin/env bash
# Generated by {generator}; Bash/Linux only.
#
# Start this master runner headlessly.  It launches exactly one model at a
# time, writes that model's PID/log under logs/, waits for completion, and
# rejects a failed or incomplete result before advancing.  It never creates
# parallel YONOD jobs and never overwrites an existing task log, PID, result,
# or verification record.
set -euo pipefail

script_dir="$(cd "$(dirname "${{BASH_SOURCE[0]}}")" && pwd)"
repo_root="$(cd "${{script_dir}}/../../.." && pwd)"
cd "$repo_root"
source /home/wangzh685/miniconda3/etc/profile.d/conda.sh
conda activate yonod

mkdir -p logs

verify_completed() {{
  local config_path="$1"
  python _verify/verify_ablation2_frozen_external_result.py --config "$config_path" >/dev/null
}}

# Preflight the two previously completed tasks before any remaining task can
# run.  This detects a changed source/audit population or damaged evidence.
{completed_checks}

task_scripts=(
{scripts}
)

for launcher in "${{task_scripts[@]}}"; do
  task_name="$(basename "$launcher" .sh)"
  config_path="config/${{task_name}}.yaml"
  result_root="result/${{task_name}}"
  log_path="logs/${{task_name}}.log"
  pid_path="logs/${{task_name}}.pid"
  verify_path="logs/${{task_name}}.verification.json"

  if [[ ! -x "$launcher" || ! -f "$config_path" ]]; then
    echo "[batch:blocked] missing launcher or config for $task_name" >&2
    exit 2
  fi
  if [[ -e "$result_root" || -e "$log_path" || -e "$pid_path" || -e "$verify_path" ]]; then
    echo "[batch:blocked] refusing to overwrite existing evidence for $task_name" >&2
    exit 2
  fi

  echo "[batch:start] $task_name"
  nohup setsid bash "$launcher" </dev/null > "$log_path" 2>&1 &
  task_pid=$!
  printf '%s\\n' "$task_pid" > "$pid_path"

  # wait is event-driven for this direct child; it is not polling and ensures
  # no next task starts while this task has a live model process.
  if wait "$task_pid"; then
    :
  else
    status=$?
    echo "[batch:failed] $task_name exit=$status; inspect $log_path" >&2
    exit "$status"
  fi

  if ! python _verify/verify_ablation2_frozen_external_result.py --config "$config_path" > "$verify_path"; then
    echo "[batch:failed] $task_name finished but its evidence verification failed" >&2
    exit 3
  fi
  echo "[batch:complete] $task_name"
done

echo "[batch:complete] {plan_id}: all {task_count} remaining tasks passed verification"
""".format(
        generator=Path(__file__).name,
        completed_checks=completed_config_lines,
        scripts=script_lines,
        plan_id=PLAN_ID,
        task_count=len(REMAINING),
    )


def preflight() -> None:
    if len(REMAINING) != 10 or len(set(REMAINING)) != len(REMAINING):
        raise RuntimeError("Frozen remaining plan must contain exactly ten unique task names")
    if set(COMPLETED).intersection(REMAINING):
        raise RuntimeError("Completed and remaining task names overlap")
    for task_name in COMPLETED:
        if not (_result_root(task_name) / "docs" / "metrics" / "external_test_metrics.csv").is_file():
            raise RuntimeError("Completed prerequisite has no metrics evidence: {0}".format(task_name))
    for task_name in REMAINING:
        config_path = _config_path(task_name)
        config = FrozenExternalTestConfig.from_file(config_path)
        if config.outputs_root != _result_root(task_name):
            raise RuntimeError("Task output root disagrees with frozen name: {0}".format(task_name))
        if config.outputs_root.exists():
            raise RuntimeError("Remaining task result root is not empty/absent: {0}".format(task_name))
        if config.models[0] not in {"rf", "lightgbm"}:
            raise RuntimeError("Unexpected model in remaining task: {0}".format(task_name))


def generate() -> list[Path]:
    preflight()
    task_paths = [TASK_DIR / (task_name + ".sh") for task_name in REMAINING]
    for task_name, path in zip(REMAINING, task_paths):
        _write_immutable(path, _task_launcher(task_name), executable=True)
    _write_immutable(MASTER, _master_runner(task_paths), executable=True)
    return [*task_paths, MASTER]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="write the frozen per-task and serial launchers")
    args = parser.parse_args()
    generated = generate() if args.write else []
    print(
        "[remaining-launchers] plan={0} tasks={1} generated={2} master={3}".format(
            PLAN_ID, len(REMAINING), len(generated), MASTER.relative_to(ROOT)
        )
    )


if __name__ == "__main__":
    main()
